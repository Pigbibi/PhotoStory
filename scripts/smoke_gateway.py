def save(root,receipt):
    fd,name=tempfile.mkstemp(prefix='.receipt-',dir=root)
    try:
        with os.fdopen(fd,'wb') as out:
            out.write(packed(receipt));out.flush();os.fsync(out.fileno())
        os.replace(name,root/'receipt.json')
        directory=os.open(root,os.O_RDONLY|os.O_DIRECTORY)
        try:os.fsync(directory)
        finally:os.close(directory)
    finally:
        if os.path.exists(name):os.unlink(name)


def read_receipt(root):
    s=root.lstat();p=root/'receipt.json';f=p.lstat()
    if (not stat.S_ISDIR(s.st_mode) or stat.S_IMODE(s.st_mode)!=0o700 or s.st_uid!=os.getuid()
        or not stat.S_ISREG(f.st_mode) or stat.S_IMODE(f.st_mode)!=0o600
        or f.st_uid!=os.getuid() or f.st_nlink!=1 or f.st_size>16000):raise Stopped('unsafe_receipt')
    r=json.loads(p.read_bytes())
    if (r.get('idempotency_key')!=IDEMPOTENCY or r.get('attempt_id')!=ATTEMPT
        or r.get('project')!=PROJECT or r.get('request_sha256')!=digest(request_body())):
        raise Stopped('receipt_binding_drift')
    return r


